import { router } from '../trpc';
import { publicProcedureWithLogging, protectedProcedure } from '../trpc';
import { z } from 'zod';
import { TRPCError } from '@trpc/server';

const flowBlockSchema = z.object({
  id: z.string(),
  type: z.enum(['start', 'add_task', 'capture_slip', 'update_budget', 'request_approval', 'start_consensus', 'notify', 'if_else', 'complete']),
  label: z.string(),
  description: z.string(),
  config: z.record(z.any()).default({}),
  color: z.string(),
});

const flowWorkflowSchema = z.object({
  id: z.string().optional(),
  name: z.string().min(1).max(200),
  description: z.string(),
  blocks: z.array(flowBlockSchema).default([]),
  isActive: z.boolean().default(true),
});

const executionLogSchema = z.object({
  id: z.string().optional(),
  flowId: z.string(),
  flowName: z.string(),
  status: z.enum(['success', 'failed', 'running']),
  idempotencyKey: z.string(),
  startedAt: z.string(),
  completedAt: z.string().optional(),
  stepResults: z.array(z.object({
    blockId: z.string(),
    blockType: z.string(),
    label: z.string(),
    output: z.string(),
    status: z.enum(['ok', 'skipped', 'error']),
  })),
});

export const flowsRouter = router({
  getAll: publicProcedureWithLogging.query(async ({ ctx }) => {
    const db = await ctx.req.app.locals.db.getDatabase();
    return { success: true, data: db.flows };
  }),

  getById: publicProcedureWithLogging
    .input(z.object({ id: z.string() }))
    .query(async ({ ctx, input }) => {
      const db = await ctx.req.app.locals.db.getDatabase();
      const flow = db.flows.find((f: any) => f.id === input.id);
      if (!flow) {
        throw new TRPCError({ code: 'NOT_FOUND', message: 'Flow not found' });
      }
      return { success: true, data: flow };
    }),

  create: protectedProcedure
    .input(flowWorkflowSchema)
    .mutation(async ({ ctx, input }) => {
      const db = await ctx.req.app.locals.db.getDatabase();
      const newFlow = {
        ...input,
        id: input.id || `flow-${Date.now()}`,
        createdAt: new Date().toISOString(),
      };
      db.flows.push(newFlow);
      await ctx.req.app.locals.db.saveDatabase(db);
      return { success: true, data: newFlow };
    }),

  update: protectedProcedure
    .input(flowWorkflowSchema.extend({ id: z.string() }))
    .mutation(async ({ ctx, input }) => {
      const db = await ctx.req.app.locals.db.getDatabase();
      const idx = db.flows.findIndex((f: any) => f.id === input.id);
      if (idx === -1) {
        throw new TRPCError({ code: 'NOT_FOUND', message: 'Flow not found' });
      }
      db.flows[idx] = { ...db.flows[idx], ...input };
      await ctx.req.app.locals.db.saveDatabase(db);
      return { success: true, data: db.flows[idx] };
    }),

  delete: protectedProcedure
    .input(z.object({ id: z.string() }))
    .mutation(async ({ ctx, input }) => {
      const db = await ctx.req.app.locals.db.getDatabase();
      db.flows = db.flows.filter((f: any) => f.id !== input.id);
      await ctx.req.app.locals.db.saveDatabase(db);
      return { success: true, message: 'Flow deleted' };
    }),

  execute: protectedProcedure
    .input(z.object({
      flowId: z.string(),
      context: z.record(z.any()).default({}),
      idempotencyKey: z.string().optional(),
    }))
    .mutation(async ({ ctx, input }) => {
      const db = await ctx.req.app.locals.db.getDatabase();
      const flow = db.flows.find((f: any) => f.id === input.flowId);
      if (!flow) {
        throw new TRPCError({ code: 'NOT_FOUND', message: 'Flow not found' });
      }
      if (!flow.isActive) {
        throw new TRPCError({ code: 'BAD_REQUEST', message: 'Flow is not active' });
      }

      const idempotencyKey = input.idempotencyKey || `idem-${Date.now()}`;
      const existingLog = db.flowExecutionLogs.find((l: any) => l.idempotencyKey === idempotencyKey);
      if (existingLog) {
        return { success: true, log: existingLog, duplicate: true };
      }

      const logId = `log-${Date.now()}`;
      const stepResults: any[] = [];
      const context = { ...input.context, amountCents: input.context.amountCents || 0 };

      for (const block of flow.blocks) {
        switch (block.type) {
          case 'start':
            stepResults.push({
              blockId: block.id,
              blockType: block.type,
              label: block.label,
              output: 'Workflow started',
              status: 'ok',
            });
            break;

          case 'add_task': {
            const generatedTask = {
              id: `task-flow-${Date.now()}`,
              title: `[FLOW AUTO] ${context.title || 'Follow-up action item'}`,
              description: `Auto-generated by workflow: ${flow.name}`,
              completed: false,
              dueDate: new Date().toISOString().split('T')[0],
              priority: 'medium' as const,
              category: 'Operations',
              subtasks: [],
              recurring: 'none' as const,
              createdAt: new Date().toISOString(),
            };
            db.tasks.unshift(generatedTask);
            stepResults.push({
              blockId: block.id,
              blockType: block.type,
              label: block.label,
              output: `Task created: "${generatedTask.title}"`,
              status: 'ok',
            });
            break;
          }

          case 'capture_slip':
            stepResults.push({
              blockId: block.id,
              blockType: block.type,
              label: block.label,
              output: 'Slip capture initiated',
              status: 'ok',
            });
            break;

          case 'update_budget':
            stepResults.push({
              blockId: block.id,
              blockType: block.type,
              label: block.label,
              output: 'Budget ledger transaction verified and synced with audit record.',
              status: 'ok',
            });
            break;

          case 'request_approval': {
            const activeProxy = db.proxies.find((p: any) => p.status === 'active');
            stepResults.push({
              blockId: block.id,
              blockType: block.type,
              label: block.label,
              output: activeProxy
                ? `Approval request routed to ${activeProxy.granteeName} (Ceiling: R ${(activeProxy.approvalCeilingCents / 100).toFixed(2)}).`
                : 'No active proxy found. Auto-escalated to Hub Owner.',
              status: 'ok',
            });
            break;
          }

          case 'start_consensus':
            stepResults.push({
              blockId: block.id,
              blockType: block.type,
              label: block.label,
              output: 'Initiated consensus vote sequence for eligible members.',
              status: 'ok',
            });
            break;

          case 'notify':
            stepResults.push({
              blockId: block.id,
              blockType: block.type,
              label: block.label,
              output: 'Dispatched in-app toast notification to active hub members.',
              status: 'ok',
            });
            break;

          case 'if_else': {
            const threshold = block.config.thresholdCents || 50000;
            const currentAmount = context.amountCents || 0;
            const conditionMet = currentAmount > threshold;
            context.conditionMet = conditionMet;
            stepResults.push({
              blockId: block.id,
              blockType: block.type,
              label: block.label,
              output: conditionMet
                ? `Condition True: Amount R ${(currentAmount / 100).toFixed(2)} exceeds threshold R ${(threshold / 100).toFixed(2)}.`
                : `Condition False: Amount R ${(currentAmount / 100).toFixed(2)} is under threshold R ${(threshold / 100).toFixed(2)}.`,
              status: 'ok',
            });
            break;
          }

          case 'complete':
            stepResults.push({
              blockId: block.id,
              blockType: block.type,
              label: block.label,
              output: 'Workflow finished successfully.',
              status: 'ok',
            });
            break;

          default:
            stepResults.push({
              blockId: block.id,
              blockType: block.type,
              label: block.label,
              output: `Executed step ${block.label}`,
              status: 'ok',
            });
        }
      }

      const executionLog = {
        id: logId,
        flowId: flow.id,
        flowName: flow.name,
        status: 'success' as const,
        idempotencyKey,
        startedAt: new Date().toISOString(),
        completedAt: new Date().toISOString(),
        stepResults,
      };

      db.flowExecutionLogs.unshift(executionLog);
      flow.lastRunAt = executionLog.completedAt;
      await ctx.req.app.locals.db.saveDatabase(db);

      return { success: true, log: executionLog };
    }),

  getExecutionLogs: publicProcedureWithLogging
    .input(z.object({ flowId: z.string().optional() }).optional())
    .query(async ({ ctx, input }) => {
      const db = await ctx.req.app.locals.db.getDatabase();
      let logs = db.flowExecutionLogs;
      if (input?.flowId) {
        logs = logs.filter((l: any) => l.flowId === input.flowId);
      }
      return { success: true, data: logs };
    }),
});